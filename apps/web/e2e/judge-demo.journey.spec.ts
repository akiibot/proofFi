import { test, expect } from './fixtures';
import { launchJudge } from './judge-helper';
import { signIn } from './auth-helper';
import { getJson, writeHeaders, TOKEN, RECIPIENT } from './api-helpers';

test('judge: explicit rules, real simulation and signed proof, isolated expense, no approval or sending', async ({ page }) => {
  test.setTimeout(180000);
  const counts: Record<string, number> = {};
  page.on('response', response => {
    const path = new URL(response.url()).pathname;
    if (!path.startsWith('/api/backend/')) return;
    counts[path] = (counts[path] ?? 0) + 1;
    if (response.status() === 429) console.log('JUDGE_RATE_DIAGNOSTIC', { path, counts });
  });
  await signIn(page);
  const before = await Promise.all(['financial-state', 'constitutions/history', 'audit'].map(route => getJson(page, route)));
  await page.setViewportSize({ width: 390, height: 844 });
  await launchJudge(page);
  await page.getByRole('link', { name: 'Rules', exact: true }).click();
  await page.getByRole('button', { name: /Set up my rules/ }).click();
  await page.getByRole('button', { name: /known address/ }).click();
  await page.getByLabel('Known recipients', { exact: true }).fill(RECIPIENT);
  await page.getByRole('button', { name: /approved test token/ }).click();
  await page.getByLabel('Allowed tokens', { exact: true }).fill(TOKEN);
  await page.getByRole('button', { name: 'Review changes' }).click();
  const review = page.getByRole('dialog', { name: 'Review draft' });
  await expect(review.getByRole('button', { name: 'Activate' })).toBeDisabled();
  expect((await getJson(page, 'financial-state')).active_constitution_version).toBeNull();
  await review.getByLabel(/Yes, make these my rules/).check();
  await review.getByRole('button', { name: 'Activate' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'is now your active rules' })).toBeVisible();
  await page.getByRole('link', { name: 'Ask', exact: true }).click();
  await page.getByLabel('What should Vallet do?').fill('Invest without risking tuition');
  await page.getByRole('button', { name: 'Check it', exact: true }).click();
  await expect(page.getByTestId('optimizer-result')).toBeVisible({ timeout: 35000 });
  await expect(page.getByTestId('safe-amount')).toHaveText(/\$/);
  await page.getByRole('button', { name: /^Continue with/ }).click();
  await expect(page.getByRole('heading', { name: 'Verified proposal' })).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole('button', { name: 'Sending disabled', exact: true })).toBeDisabled();
  const id = new URL(page.url()).searchParams.get('id')!;
  const cert = await getJson(page, `certificates/${id}`);
  expect(cert.verifier_signature).toMatch(/^[0-9a-f]{128}$/);
  const headers = await writeHeaders(page);
  const checked = await page.request.post(`/api/backend/certificates/${id}/verify`, { headers });
  expect((await checked.json()).signature_valid).toBe(true);
  expect((await page.request.post('/api/backend/approvals', { headers, data: { certificate_id: id, action_digest: cert.payload.action_digest, decision: 'APPROVE' } })).status()).toBe(403);
  expect((await page.request.post('/api/backend/execute', { headers, data: { certificate_id: id, action_digest: cert.payload.action_digest, idempotency_key: 'judge-must-never-send-001' } })).status()).toBe(403);
  await page.getByRole('link', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: 'Record an expense', exact: true }).click();
  const expense = page.getByRole('dialog', { name: 'Record an unexpected expense' });
  await expense.getByLabel(/Yes, record this/).check();
  await expense.getByRole('button', { name: 'Record expense', exact: true }).click();
  await expect(expense).toHaveCount(0, { timeout: 15000 });
  const afterResponse = await page.request.get('/api/backend/financial-state');
  expect(afterResponse.status()).toBe(200);
  const afterExpense = await afterResponse.json();
  expect(afterExpense.snapshot.version).toBe(3);
  const guestAudit = await getJson(page, 'audit');
  expect(guestAudit.some((e: {event_type: string}) => /EXECUTION|APPROVAL_RECORDED/.test(e.event_type))).toBe(false);
  await signIn(page);
  const after = await Promise.all(['financial-state', 'constitutions/history', 'audit'].map(route => getJson(page, route)));
  expect(after).toEqual(before);
});
